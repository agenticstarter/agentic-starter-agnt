/**
 * Copies contract ABIs into packages/sdk/src/abis.js so the web apps, indexer and CLI
 * stay in sync with the Solidity sources. Run after `npx hardhat compile`.
 */
const fs = require("fs");
const path = require("path");

const NAMES = ["AgentLaunchpad", "LaunchpadLens", "LaunchToken", "AGNTToken", "AGNTStaking", "AGNTPresale", "SparkAirdrop", "FeeSplitter", "IgniteBoard", "AGNTVesting", "AgentGate", "TestnetAgentID", "AccountFeeEscrow", "StandardTokenFactory", "BasicToken", "AdvancedToken", "LiquidityHelper", "LaunchRules"];
const root = path.join(__dirname, "..");
let out = "// Generated by contracts/scripts/export-abi.js — do not edit by hand.\n\n";
for (const n of NAMES) {
  const file = ["BasicToken", "AdvancedToken", "StandardTokenFactory", "LiquidityHelper"].includes(n) ? "StandardTokens" : n;
  const art = JSON.parse(fs.readFileSync(path.join(root, "artifacts", "contracts", `${file}.sol`, `${n}.json`), "utf8"));
  out += `export const ${n}Abi = /** @type {const} */ (${JSON.stringify(art.abi)});\n\n`;
}
const dest = path.join(root, "..", "packages", "sdk", "src", "abis.js");
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log(`wrote ${path.relative(process.cwd(), dest)}`);
